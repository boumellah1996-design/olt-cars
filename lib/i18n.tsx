export type Dictionary = typeof dictionary.fr;

export const LOCALES: { id: Locale; native: string; short: string }[] = [
  { id: "ar", native: "العربية", short: "AR" },
  { id: "fr", native: "Français", short: "FR" },
  { id: "en", native: "English", short: "EN" },
  { id: "es", native: "Español", short: "ES" },
];

export function isLocale(value: string | null): value is Locale {
  return value === "ar" || value === "fr" || value === "en" || value === "es";
}

type I18nContextValue = {
  locale: Locale;
  t: Dictionary;
  setLocale: (locale: Locale) => void;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocale] = useState<Locale>("fr");
  const [ready, setReady] = useState(false);

  useEffect(() => {
    const saved = window.localStorage.getItem("olt-locale");
    if (isLocale(saved)) setLocale(saved);
    setReady(true);
  }, []);

  useEffect(() => {
    if (!ready) return;
    window.localStorage.setItem("olt-locale", locale);
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
    document.documentElement.classList.toggle("font-arabic", locale === "ar");
  }, [locale, ready]);

  const value = useMemo(
    () => ({
      locale,
      t: dictionary[locale] as Dictionary,
      setLocale,
    }),
    [locale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
